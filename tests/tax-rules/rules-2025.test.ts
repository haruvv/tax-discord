import { describe, expect, test } from "vitest";
import { rules2025 } from "../../scripts/tax-rules/2025.js";

describe("calcSalaryDeduction（R7改正後）", () => {
  test.each([
    // 190万以下 → 65万
    [0, 650_000],
    [1_900_000, 650_000],
    // 190万超〜360万 → revenue * 0.3 + 80_000
    [1_900_001, Math.floor(1_900_001 * 0.3 + 80_000)],
    [3_600_000, Math.floor(3_600_000 * 0.3 + 80_000)],
    // 360万超〜660万 → revenue * 0.2 + 440_000
    [3_600_001, Math.floor(3_600_001 * 0.2 + 440_000)],
    [6_600_000, Math.floor(6_600_000 * 0.2 + 440_000)],
    // 660万超〜850万 → revenue * 0.1 + 1_100_000
    [6_600_001, Math.floor(6_600_001 * 0.1 + 1_100_000)],
    [8_500_000, Math.floor(8_500_000 * 0.1 + 1_100_000)],
    // 850万超 → 195万
    [8_500_001, 1_950_000],
    [20_000_000, 1_950_000],
  ])("収入 %i → 控除 %i", (revenue, expected) => {
    expect(rules2025.calcSalaryDeduction(revenue)).toBe(expected);
  });
});

describe("calcBasicDeduction（R7改正後・特例含む）", () => {
  test.each([
    // 132万以下 → 95万
    [0, 950_000],
    [1_320_000, 950_000],
    // 132万超〜336万 → 88万
    [1_320_001, 880_000],
    [3_360_000, 880_000],
    // 336万超〜489万 → 68万
    [3_360_001, 680_000],
    [4_890_000, 680_000],
    // 489万超〜655万 → 63万
    [4_890_001, 630_000],
    [6_550_000, 630_000],
    // 655万超〜2350万 → 58万
    [6_550_001, 580_000],
    [23_500_000, 580_000],
    // 2350万超〜2400万 → 48万
    [23_500_001, 480_000],
    [24_000_000, 480_000],
    // 2400万超〜2450万 → 32万
    [24_000_001, 320_000],
    [24_500_000, 320_000],
    // 2450万超〜2500万 → 16万
    [24_500_001, 160_000],
    [25_000_000, 160_000],
    // 2500万超 → 0
    [25_000_001, 0],
  ])("合計所得 %i → 基礎控除 %i", (totalIncome, expected) => {
    expect(rules2025.calcBasicDeduction(totalIncome)).toBe(expected);
  });
});

describe("calcIncomeTax（所得税率ブラケット）", () => {
  test("課税所得 0 → 0", () => {
    expect(rules2025.calcIncomeTax(0)).toBe(0);
  });

  test("負の値 → 0", () => {
    expect(rules2025.calcIncomeTax(-100)).toBe(0);
  });

  test.each([
    // 5%ブラケット (〜195万)
    [1_000_000, 1_000_000 * 0.05 - 0],
    [1_950_000, 1_950_000 * 0.05 - 0],
    // 10%ブラケット (195万超〜330万)
    [2_000_000, 2_000_000 * 0.10 - 97_500],
    [3_300_000, 3_300_000 * 0.10 - 97_500],
    // 20%ブラケット (330万超〜695万)
    [5_000_000, 5_000_000 * 0.20 - 427_500],
    [6_950_000, 6_950_000 * 0.20 - 427_500],
    // 23%ブラケット (695万超〜900万)
    [8_000_000, 8_000_000 * 0.23 - 636_000],
    [9_000_000, 9_000_000 * 0.23 - 636_000],
    // 33%ブラケット (900万超〜1800万)
    [10_000_000, 10_000_000 * 0.33 - 1_536_000],
    [18_000_000, 18_000_000 * 0.33 - 1_536_000],
    // 40%ブラケット (1800万超〜4000万)
    [20_000_000, 20_000_000 * 0.40 - 2_796_000],
    [40_000_000, 40_000_000 * 0.40 - 2_796_000],
    // 45%ブラケット (4000万超)
    [50_000_000, 50_000_000 * 0.45 - 4_796_000],
  ])("課税所得 %i → 税額 %i", (taxable, expected) => {
    expect(rules2025.calcIncomeTax(taxable)).toBe(expected);
  });
});
